#!/usr/bin/env node
/**
 * Writes src/sky/solarPositionTerms.ts from the tables of the report the
 * solar position algorithm comes from:
 *
 *   Reda, I. and Andreas, A., "Solar Position Algorithm for Solar Radiation
 *   Applications", NREL/TP-560-34302, revised January 2008,
 *   Table A4.2 (Earth periodic terms) and Table A4.3 (nutation terms).
 *
 * The numbers are the report's; no code of NREL's is used. Get the report's
 * text with poppler, then run this on it:
 *
 *   pdftotext -layout 34302.pdf spa-layout.txt
 *   node scripts/sky/extract-spa-terms.mjs spa-layout.txt
 *
 * src/sky/solarPosition.test.ts checks every series these tables give against
 * the sums the report prints for its example (Table A5.1), so a number read
 * wrongly here fails there.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/sky/extract-spa-terms.mjs <pdftotext -layout output of NREL/TP-560-34302>");
  process.exit(1);
}
const lines = readFileSync(input, "utf8").split(/\r?\n/);
const start = lines.findIndex(line => /^\s*Table A4\.2\. Earth Periodic Terms\s*$/.test(line));
const nutationStart = lines.findIndex(line => /^\s*Table A4\.3\. Periodic Terms for the Nutation/.test(line) && !/\. \. \./.test(line));
const end = lines.findIndex((line, index) => index > nutationStart && /^\s*A\.5\.\s+Example/.test(line));
if (start < 0 || nutationStart < start || end < nutationStart) throw new Error("The report's tables were not found in this text.");

/** Rows of each series the report's Table A4.2 holds. */
const EXPECTED_ROWS = { L0: 64, L1: 34, L2: 20, L3: 7, L4: 3, L5: 1, B0: 5, B1: 2, R0: 40, R1: 10, R2: 6, R3: 2, R4: 1 };
const NUMBER = "-?\\d+(?:\\.\\d+)?";
const termRow = new RegExp(`^\\s*(?:([LBR]\\d)\\s+)?(\\d+)\\s+(${NUMBER})\\s+(${NUMBER})\\s+(${NUMBER})\\s*$`);
const series = {};
let current = null;
for (const line of lines.slice(start + 1, nutationStart)) {
  const match = termRow.exec(line);
  if (!match) continue;
  if (match[1]) {
    current = match[1];
    series[current] = [];
  }
  if (!current) throw new Error(`A row came before any series: ${line}`);
  const row = Number(match[2]);
  if (row !== series[current].length) throw new Error(`${current} row ${row} follows row ${series[current].length - 1}: ${line}`);
  series[current].push([Number(match[3]), Number(match[4]), Number(match[5])]);
}
for (const [name, rows] of Object.entries(EXPECTED_ROWS)) {
  if (series[name]?.length !== rows) throw new Error(`${name}: read ${series[name]?.length ?? 0} rows, the report has ${rows}.`);
}

// Table A4.3: five multipliers Y0..Y4, then a, b, c, d with blanks for zero.
// a and c are whole numbers of 0.0001"; b and d are their rates and always
// written with a decimal point, which is how a blank between them is found.
const nutation = [];
for (const line of lines.slice(nutationStart + 1, end)) {
  const tokens = line.trim().split(/\s+/);
  if (tokens.length < 6 || tokens.length > 9 || !tokens.every(token => new RegExp(`^${NUMBER}$`).test(token))) continue;
  const y = tokens.slice(0, 5).map(Number);
  if (!y.every(Number.isInteger)) continue;
  const rest = tokens.slice(5);
  const a = Number(rest.shift());
  let b = 0, c = 0, d = 0;
  if (rest.length > 0 && rest[0].includes(".")) b = Number(rest.shift());
  if (rest.length > 0 && !rest[0].includes(".")) c = Number(rest.shift());
  if (rest.length > 0 && rest[0].includes(".")) d = Number(rest.shift());
  if (rest.length > 0) throw new Error(`Nutation row not understood: ${line}`);
  nutation.push([...y, a, b, c, d]);
}
if (nutation.length !== 63) throw new Error(`Nutation: read ${nutation.length} rows, the report has 63.`);

const rows = values => values.map(row => `    [${row.join(", ")}],`).join("\n");
const group = prefix => Object.keys(EXPECTED_ROWS).filter(name => name.startsWith(prefix))
  .map(name => `  [ // ${name}\n${rows(series[name])}\n  ],`).join("\n");
const output = `/**
 * Generated by scripts/sky/extract-spa-terms.mjs. Do not edit.
 *
 * The periodic terms of the solar position algorithm of Reda and Andreas,
 * "Solar Position Algorithm for Solar Radiation Applications",
 * NREL/TP-560-34302 (revised January 2008): Table A4.2, the Earth's
 * heliocentric longitude (L0 to L5), latitude (B0, B1) and radius vector (R0
 * to R4), each row A, B, C of A * cos(B + C * JME); and Table A4.3, the
 * nutation in longitude and obliquity, each row Y0 to Y4, a, b, c, d.
 */

export const SPA_LONGITUDE_TERMS: readonly (readonly (readonly [number, number, number])[])[] = [
${group("L")}
];

export const SPA_LATITUDE_TERMS: readonly (readonly (readonly [number, number, number])[])[] = [
${group("B")}
];

export const SPA_RADIUS_TERMS: readonly (readonly (readonly [number, number, number])[])[] = [
${group("R")}
];

export const SPA_NUTATION_TERMS: readonly (readonly number[])[] = [
${rows(nutation)}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "sky", "solarPositionTerms.ts");
writeFileSync(target, output);
console.log(`Wrote ${target}: ${Object.entries(EXPECTED_ROWS).map(([name, count]) => `${name} ${count}`).join(", ")}, nutation ${nutation.length}.`);
