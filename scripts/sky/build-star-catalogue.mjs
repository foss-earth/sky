#!/usr/bin/env node
/**
 * Writes src/sky/starCatalogue.ts from the Bright Star Catalogue, 5th revised
 * edition (Hoffleit and Warren, 1991), as the CDS distributes it (V/50):
 *
 *   curl -A "foss-earth-check/1.0" -O https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz
 *   gunzip catalog.gz
 *   node scripts/sky/build-star-catalogue.mjs catalog
 *
 * It keeps, for each of the 9,096 stars with a position, its J2000 right
 * ascension and declination, its V magnitude, its B−V colour and its proper
 * motion, in the byte columns the catalogue's ReadMe gives. Nothing else of
 * the catalogue is used. src/sky/stars.test.ts checks stars it can name.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/sky/build-star-catalogue.mjs <V/50 catalog>");
  process.exit(1);
}

/** A field by the ReadMe's 1-based, inclusive byte columns, or null where it is blank. */
const field = (line, from, to) => {
  const text = line.slice(from - 1, to).trim();
  return text === "" ? null : text;
};

/** B−V for the few stars the catalogue gives none: the Sun's, so they are drawn white. */
const MISSING_COLOUR_INDEX = 0.65;
const STRIDE = 16;

const stars = [];
for (const line of readFileSync(input, "latin1").split(/\r?\n/)) {
  const raHours = field(line, 76, 77);
  const vmag = field(line, 103, 107);
  if (raHours === null || vmag === null) continue;
  const ra = (Number(raHours) + Number(field(line, 78, 79)) / 60 + Number(field(line, 80, 83)) / 3600) * 15;
  const sign = field(line, 84, 84) === "-" ? -1 : 1;
  const dec = sign * (Number(field(line, 85, 86)) + Number(field(line, 87, 88)) / 60 + Number(field(line, 89, 90)) / 3600);
  const bv = field(line, 110, 114);
  const pmRa = field(line, 149, 154);
  const pmDec = field(line, 155, 160);
  stars.push({ ra, dec, vmag: Number(vmag), bv: bv === null ? MISSING_COLOUR_INDEX : Number(bv), pmRa: Number(pmRa ?? 0), pmDec: Number(pmDec ?? 0) });
}
// Brightest first, so a limit on magnitude is a prefix.
stars.sort((a, b) => a.vmag - b.vmag);

const bytes = new Uint8Array(stars.length * STRIDE);
const view = new DataView(bytes.buffer);
stars.forEach((star, index) => {
  const at = index * STRIDE;
  view.setFloat32(at, star.ra, true);
  view.setFloat32(at + 4, star.dec, true);
  view.setInt16(at + 8, Math.round(star.vmag * 100), true);
  view.setInt16(at + 10, Math.round(star.bv * 1000), true);
  view.setInt16(at + 12, Math.round(star.pmRa * 1000), true);
  view.setInt16(at + 14, Math.round(star.pmDec * 1000), true);
});
const base64 = Buffer.from(bytes).toString("base64");
const chunks = base64.match(/.{1,120}/g) ?? [];

const target = join(dirname(fileURLToPath(import.meta.url)), "../../src/sky/starCatalogue.ts");
writeFileSync(target, `/**
 * Generated by scripts/sky/build-star-catalogue.mjs. Do not edit.
 *
 * The ${stars.length.toLocaleString("en-US")} stars of the Bright Star Catalogue, 5th revised edition
 * (D. Hoffleit and W. H. Warren Jr., 1991; CDS catalogue V/50), brightest
 * first, ${STRIDE} bytes each, little-endian: J2000 right ascension and
 * declination (float32, degrees), V magnitude × 100 and B−V × 1000 (int16),
 * and proper motion in right ascension, as cos δ × dα/dt, and in declination
 * (int16, milliarcseconds a year).
 */

export const STAR_RECORD_BYTES = ${STRIDE};

export const STAR_RECORDS = [
${chunks.map(chunk => `  "${chunk}",`).join("\n")}
].join("");
`);
console.log(`${stars.length} stars, ${bytes.length} bytes, written to ${target}`);
